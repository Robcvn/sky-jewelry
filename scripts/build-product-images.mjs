// Builds the product card photos from shopify/images/*.jpg (the same files Shopify imports):
// square WebP files in public/images/products at the widths the cards need, and
// src/content/product-image-manifest.ts. Stands in for Sanity's / Shopify's image pipeline.
// Widths: 342 (mobile card 171px at 2x), 640 (desktop card 300px and its 320px hover zoom at 2x),
// 748 (mobile quick view 374px at 2x). Never upscales: widths above the source are dropped, and a source narrower than
// 640 adds its own width instead.
// Run: npm run images:products
//
// Gallery-only mode (npm run images:gallery, or --gallery): writes only public/images/products/gallery and
// src/content/product-gallery-manifest.ts, and touches no other file. Each photo gets the widths its full-size
// slots need at 1x and 2x, never upscaled past the source (the largest file is then the source's own width):
//   <key>-gallery-m      mobile product gallery, 390px tile: 390 and 780
//   <key>-quickview      quick view photo, 374px at 390 (368px on desktop): 374 and 748
//   <key>-gallery-d-wide desktop gallery first tile when it spans the row, 694px at 1440: 694 and 1388
//                        (main photos only: worn, angled and close-up views never take that tile)
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const SOURCE = "shopify/images";
const OUT = "public/images/products";
const MANIFEST = "src/content/product-image-manifest.ts";
const WIDTHS = [342, 640, 748];
// The loose stones' photos (stone-*.jpg) are in the same folder for the builder's Shopify import, but the site shows
// them from the builder's own crops (src/lib/builder.ts), so they get no card files here.
const isProductPhoto = (name) => name.endsWith(".jpg") && !name.startsWith("stone-");

if (process.argv.includes("--gallery")) {
  const GALLERY_OUT = path.join(OUT, "gallery");
  const GALLERY_MANIFEST = "src/content/product-gallery-manifest.ts";
  const SLOTS = { "gallery-m": [390, 780], quickview: [374, 748], "gallery-d-wide": [694, 1388] };
  fs.rmSync(GALLERY_OUT, { recursive: true, force: true });
  fs.mkdirSync(GALLERY_OUT, { recursive: true });
  const gallery = {};
  let bytes = 0;
  for (const file of fs.readdirSync(SOURCE).filter(isProductPhoto).sort()) {
    const name = path.basename(file, ".jpg");
    const input = path.join(SOURCE, file);
    const { width } = await sharp(input).metadata();
    const written = new Set();
    for (const [slot, wanted] of Object.entries(slotsFor(name))) {
      const widths = [...new Set(wanted.map((w) => Math.min(w, width)))];
      gallery[`product-${name}-${slot}`] = widths.map((w) => ({ src: `/images/products/gallery/${name}-${w}.webp`, w, h: w }));
      for (const w of widths) {
        if (written.has(w)) continue;
        written.add(w);
        const out = path.join(GALLERY_OUT, `${name}-${w}.webp`);
        await sharp(input).resize(w, w, { fit: "cover" }).webp({ quality: 74, effort: 6 }).toFile(out);
        bytes += fs.statSync(out).size;
      }
    }
  }
  function slotsFor(name) {
    return /-(worn|angled|closeup)$/.test(name) ? { "gallery-m": SLOTS["gallery-m"], quickview: SLOTS.quickview } : SLOTS;
  }
  fs.writeFileSync(
    GALLERY_MANIFEST,
    `// Generated by scripts/build-product-images.mjs --gallery from shopify/images. Do not edit by hand.
// Full-size slot crops of the product photos (mobile gallery, quick view, the desktop gallery's wide tile).
export const productGalleryManifest = ${JSON.stringify(gallery, null, 2)} as const;

export type ProductGalleryKey = keyof typeof productGalleryManifest;
`,
  );
  console.log(`Wrote ${Object.keys(gallery).length} gallery entries, ${Math.round(bytes / 1024)} KB of WebP, and ${GALLERY_MANIFEST}`);
  process.exit(0);
}

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

const manifest = {};
let total = 0;
for (const file of fs.readdirSync(SOURCE).filter(isProductPhoto).sort()) {
  const name = path.basename(file, ".jpg");
  const input = path.join(SOURCE, file);
  const { width } = await sharp(input).metadata();
  const widths = WIDTHS.filter((w) => w <= width);
  // A source narrower than the desktop card's 640 also gets a file at its own width (Task 32): without it, wide screens
  // (cards up to 420px at 1920, 574 in the 2560 carousels) were left with the 342 file. Still never upscaled.
  if (width < WIDTHS[1] && !widths.includes(width)) widths.push(width);
  manifest[`product-${name}`] = [];
  for (const w of widths) {
    const out = `${name}-${w}.webp`;
    await sharp(input).resize(w, w, { fit: "cover" }).webp({ quality: 74, effort: 6 }).toFile(path.join(OUT, out));
    total += fs.statSync(path.join(OUT, out)).size;
    manifest[`product-${name}`].push({ src: `/images/products/${out}`, w, h: w });
  }
}

fs.writeFileSync(
  MANIFEST,
  `// Generated by scripts/build-product-images.mjs from shopify/images. Do not edit by hand.
export const productImageManifest = ${JSON.stringify(manifest, null, 2)} as const;

export type ProductImageKey = keyof typeof productImageManifest;
`,
);
console.log(`Wrote ${Object.keys(manifest).length} product photos, ${Math.round(total / 1024)} KB of WebP, and ${MANIFEST}`);
