// Builds src/icons/icon-data.ts from the Figma SVG exports in src/icons/svg.
// To add an icon: export it from Figma as SVG, save it there as kebab-case.svg, run npm run icons.
import fs from "node:fs";
import path from "node:path";

const sourceDir = path.resolve("src/icons/svg");
const outFile = path.resolve("src/icons/icon-data.ts");

const entries = fs
  .readdirSync(sourceDir)
  .filter((file) => file.endsWith(".svg"))
  .sort()
  .map((file) => {
    const svg = fs.readFileSync(path.join(sourceDir, file), "utf8");
    const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
    const inner = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/)?.[1];
    if (!viewBox || !inner) throw new Error(`Could not read ${file}`);
    const [, , w, h] = viewBox.split(/\s+/);
    // Figma adds a clip the size of the icon frame. The SVG already clips to its viewBox, and the clip ids
    // would repeat when an icon shows more than once on a page, so full-frame clips are removed.
    const fullClips = [...inner.matchAll(/<clipPath id="([^"]+)">\s*<rect width="(\d+)" height="(\d+)"[^>]*\/>\s*<\/clipPath>/g)]
      .filter(([, , cw, ch]) => cw === w && ch === h)
      .map(([whole, id]) => ({ whole, id }));
    let cleaned = inner;
    for (const { whole, id } of fullClips) {
      cleaned = cleaned.replace(whole, "").replaceAll(` clip-path="url(#${id})"`, "");
    }
    cleaned = cleaned.replace(/<defs>\s*<\/defs>/g, "");
    if (/clip-path|<clipPath/.test(cleaned)) throw new Error(`${file} has a clip that is not full-frame`);
    const body = cleaned
      .replace(/\s*\n\s*/g, "")
      // Figma leaves stroke-width out when the weight is its default 1px (the 48px SealCheck, Package and
      // Certificate). Figma keeps that 1px at every size the icon is placed at (48, 32, 24), so outline paths
      // get it as a non-scaling stroke. 0.99, not 1: Chrome draws an exactly-1px curved stroke as a dotted
      // hairline at 1x; 0.99 renders solid there and looks the same. Filled paths (Star) are left alone.
      .replace(/<path(?![^>]*stroke-width=)(?![^>]*\sfill=)([^>]*\sstroke="[^"]+")/g, '<path stroke-width="0.99"$1')
      .replace(/fill="#D9D9D9"/gi, 'fill="var(--icon-accent, #d9d9d9)"')
      .replace(/(stroke|fill)="(?!none|var\()[^"]+"/gi, '$1="currentColor"')
      .replace(/stroke-width="/g, 'vector-effect="non-scaling-stroke" stroke-width="');
    return [file.replace(/\.svg$/, ""), { viewBox, body }];
  });

const data = JSON.stringify(Object.fromEntries(entries), null, 2);
fs.writeFileSync(
  outFile,
  `// Generated by scripts/build-icons.mjs. Do not edit by hand.\nexport const iconData = ${data} as const;\n\nexport type IconName = keyof typeof iconData;\n`,
);
console.log(`Wrote ${entries.length} icons`);

// Metal badges (Figma "Metal - 14k Yellow Gold" and the rest) from src/icons/metals. They are drawn inline by
// MetalBadge, not as <img>: their Glow layer uses mix-blend-mode overlay, which only reaches the tile behind the
// badge when the SVG is part of the page. Gradient ids are made unique per badge by MetalBadge.
const badgeDir = path.resolve("src/icons/metals");
const badgeFile = path.resolve("src/icons/metal-badge-data.ts");
const badges = fs
  .readdirSync(badgeDir)
  .filter((file) => file.endsWith(".svg"))
  .sort()
  .map((file) => {
    const svg = fs.readFileSync(path.join(badgeDir, file), "utf8");
    const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
    const inner = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/)?.[1];
    if (!viewBox || !inner) throw new Error(`Could not read ${file}`);
    return [file.replace(/\.svg$/, ""), { viewBox, body: inner.replace(/\s*\n\s*/g, "") }];
  });
fs.writeFileSync(
  badgeFile,
  `// Generated by scripts/build-icons.mjs from src/icons/metals. Do not edit by hand.\nexport const metalBadgeData = ${JSON.stringify(Object.fromEntries(badges), null, 2)} as const;\n`,
);
console.log(`Wrote ${badges.length} metal badges`);
